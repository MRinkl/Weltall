	FGlyph SmallGlyph(char Code)
	{
		for (const FSmallEntry& Entry : SmallFont)
		{
			if (Entry.Code == Code)
			{
				return {Entry.Code, Entry.Rows};
			}
		}
		return {};
	}

	FGlyph BigGlyph(char Code)
	{
		for (const FBigEntry& Entry : BigFont)
		{
			if (Entry.Code == Code)
			{
				return {Entry.Code, Entry.Rows};
			}
		}
		return {};
	}
