	constexpr uint32 Seed = 0x1A7E0000;
	constexpr int32 Cases = 400;

	int32 Draw(FXorShift32& G, int32 Count)
	{
		return static_cast<int32>(G.Next() % static_cast<uint32>(Count));
	}

	/** 0 half the time, else Draw() - Offset of Count. */
	int32 Maybe(FXorShift32& G, int32 Count, int32 Offset)
	{
		return Draw(G, 2) == 0 ? 0 : Draw(G, Count) - Offset;
	}

	int32 TruncatedThird(int32 Value)
	{
		return Value / 3;
	}

	int32 Fixed(int32 Whole, uint32 Fraction)
	{
		return static_cast<int32>(static_cast<uint32>(Whole) << 16) + static_cast<int32>(Fraction & 0xFFFF);
	}

	class FOneSprite final : public IFieldActorModels
	{
	public:
		std::optional<FFieldSpriteResult> LoadSprite(const FFieldSpriteRequest&) override { return std::nullopt; }
		FSprite* ActorSprite(int32 Actor) override { return Actor == 0 ? &Sprite : nullptr; }
		FSpriteSystem* SpriteSystem() override { return nullptr; }
		void SwapSprites(int32, int32) override {}
		bool LoadExtraAnimations(int32, int32) override { return false; }
		void UseExtraAnimations(int32) override {}

		FSprite Sprite;
	};

	/** One case's actor, sprite and field, drawn as the oracle installs them; returns the platform's height. */
	std::optional<int32> DrawCase(FXorShift32& G, const FFieldWalkmesh& Walkmesh, FEventContext& Context, FSprite& Sprite)
	{
		const int32 Walking = static_cast<int32>(Walkmesh.Layers.size()) - 1;
		const int32 Layer = Draw(G, Walking);
		const FWalkmeshLayer& Own = Walkmesh.Layers[static_cast<std::size_t>(Layer)];
		const int32 Triangle = Draw(G, static_cast<int32>(Own.Triangles.size()));
		int32 SumX = 0;
		int32 SumZ = 0;
		for (const uint16 Vertex : Own.Triangles[static_cast<std::size_t>(Triangle)].Vertices)
		{
			SumX += Own.Vertices[Vertex][0];
			SumZ += Own.Vertices[Vertex][2];
		}
		const int32 X = TruncatedThird(SumX);
		const int32 Z = TruncatedThird(SumZ);
		FEventActorState State;
		for (int32 Other = 0; Other < Walking; ++Other)
		{
			State.FloorTriangles[static_cast<std::size_t>(Other)] = static_cast<int16>(Other == Layer ? Triangle : FindFieldFloor(Walkmesh.Layers[static_cast<std::size_t>(Other)], X, Z).Triangle);
		}
		if (Walking > 1 && Draw(G, 16) == 0)
		{
			const int32 Other = (Layer + 1 + Draw(G, Walking - 1)) % Walking;
			State.FloorTriangles[static_cast<std::size_t>(Other)] = -1;
		}
		const int32 Floor = FindFieldFloor(Own, X, Z).Height;
		const int32 Feet = Floor + Maybe(G, 129, 64);
		const uint32 A = G.Next();
		const uint32 B = G.Next();
		const uint32 C = G.Next();
		const uint32 D = G.Next();
		const uint32 E = G.Next();
		const uint32 F = G.Next();
		const uint32 H = G.Next();
		State.Flags0 = (A & B & 0x01010000) | (C & D & 0x04440000) | (E & 0x1800) | (F & H & 0x700);
		const uint32 I = G.Next();
		const uint32 J = G.Next();
		const uint32 K = G.Next();
		const uint32 L = G.Next();
		const uint32 M = G.Next();
		State.Flags1 = (I & J & K & 0x200007) | (L & M & 0x38);
		State.Layer = static_cast<uint16>(Layer);
		State.Height = static_cast<uint16>(0x30 + Draw(G, 0x51));
		const uint32 FractionX = G.Next();
		const uint32 FractionY = G.Next();
		const uint32 FractionZ = G.Next();
		State.Position = {Fixed(X, FractionX), Fixed(Feet, FractionY), Fixed(Z, FractionZ)};
		if (Draw(G, 4) != 0)
		{
			const int32 StepX = Draw(G, 49) - 24;
			const uint32 StepFractionX = G.Next();
			const int32 StepY = Draw(G, 2001) - 1000;
			const int32 StepZ = Draw(G, 49) - 24;
			const uint32 StepFractionZ = G.Next();
			State.Step = {Fixed(StepX, StepFractionX), StepY, Fixed(StepZ, StepFractionZ)};
		}
		State.FloorHeight = static_cast<int16>(Floor + Draw(G, 17) - 8);
		State.LinkedActor = static_cast<uint8>(Draw(G, 4) != 0 ? 0xFF : Draw(G, 8));
		State.TargetHeight = static_cast<int16>(Floor + Draw(G, 33) - 16);
		State.WordF0 = static_cast<int32>(G.Next());
		State.Facing = static_cast<uint16>(G.Next());
		State.Animation = static_cast<uint16>(G.Next());
		Context.States = {State};
		Context.Actors.assign(1, FFieldActor{});
		Context.Actors[0].Translation = {X, Feet, Z};
		Sprite = FSprite{};
		Sprite.Position = State.Position;
		Sprite.Velocity[1] = Maybe(G, 0x80001, 0x40000);
		const bool bUsualGravity = Draw(G, 2) == 0;
		Sprite.Gravity = bUsualGravity ? 0x20000 : Draw(G, 0x40001);
		Sprite.FloorY = static_cast<int16>(Floor + Maybe(G, 65, 32));
		Context.LeaderActor = static_cast<uint8>(Draw(G, 2) == 0 ? 0 : 1);
		Context.Controls.bFollowClose = Draw(G, 4) == 0;
		Context.Movement.bFirstTickDone = Draw(G, 4) != 0;
		Context.bPartyWalking = Draw(G, 8) == 0;
		Context.Controls.WalkMask = static_cast<uint16>(G.Next());
		Context.Controls.TrailIndices[0] = static_cast<uint32>(Draw(G, 32));
		Context.Controls.bTrailStepped = false;
		if (Draw(G, 4) == 0)
		{
			return Floor + Draw(G, 33) - 16;
		}
		return std::nullopt;
	}

	void DigestStep(FOracleDigest& Digest, const FFollowStep& Step)
	{
		Digest.I32(Step.Flags0, Step.Flags1);
		Digest.I16(Step.Position[0], Step.Position[1], Step.Position[2], Step.LandingHeight, Step.Animation, Step.Facing);
		Digest.I16(Step.FloorTriangles[0], Step.FloorTriangles[1], Step.FloorTriangles[2], Step.FloorTriangles[3]);
		Digest.I32(Step.Velocity[0], Step.Velocity[1], Step.Velocity[2], Step.FloorNormal[0], Step.FloorNormal[1], Step.FloorNormal[2]);
		Digest.I32(Step.FloorAttributes);
		Digest.U8(Step.Layer);
	}

	std::string MapDigest(FFieldMap& Map, int32 Number)
	{
		FXorShift32 G(Seed + static_cast<uint32>(Number));
		FOracleDigest Digest;
		FEventContext Context;
		Context.Walkmesh = &Map.Walkmesh;
		FOneSprite Sprites;
		Context.Models = &Sprites;
		for (int32 Case = 0; Case < Cases; ++Case)
		{
			const std::optional<int32> Platform = DrawCase(G, Map.Walkmesh, Context, Sprites.Sprite);
			const uint32 Head = Context.Controls.TrailIndices[0];
			REQUIRE(StepWalkLayer(Context, 0, Platform));
			for (const uint8 Byte : Testing::ToOriginalLayout(Context.States[0]))
			{
				Digest.U8(Byte);
			}
			const FSprite& Sprite = Sprites.Sprite;
			Digest.I32(Sprite.Position[0], Sprite.Position[1], Sprite.Position[2], Sprite.Velocity[0], Sprite.Velocity[1], Sprite.Velocity[2]);
			Digest.I16(Sprite.FloorY);
			const auto& Translation = Context.Actors[0].Translation;
			Digest.I32(Translation[0], Translation[1], Translation[2]);
			Digest.I16(Context.Controls.WalkMask);
			Digest.I32(Context.Controls.TrailIndices[0], Context.Controls.bTrailStepped ? 0u : 0xFFFFFFFFu);
			DigestStep(Digest, Context.Controls.Trail[Head]);
		}
		return Digest.Hex();
	}
