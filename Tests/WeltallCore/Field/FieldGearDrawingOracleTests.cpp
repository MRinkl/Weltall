// Digests of the gears' drawing as the game draws them, generated by the oracle:
// the game's gears' module and the kernel's MDL builder and part
// drawing under the oracle harness, each case one gear model (every model once, one case in four a
// second one) loaded as the field loads it, a random bone given a billboard mode one case in three,
// random gears' lights and a random view, then 12 ticks of random animations, the field's writes into
// each model and the drawing into an ordering table. Each tick's digest walks the table far to near,
// every packet's source, entry, code, corners, colours, texels, CLUT and page.

